"""Bakes nvshaders/sheen_albedo_table.h.slang: the directional albedo of the path tracer's sheen
lobe (brdf_sheen_sample: the Charlie distribution's half vectors, v-cavities masking, the flip toward
the view) with a white sheen colour, over sqrt(perceptual sheen roughness) and sqrt(N.V). The lobe
weights charge the layers below by it (KHR_materials_sheen's albedo scaling), and the lobe is divided
by it. The albedo moves fastest at low roughness, where a linear 16-row table was 0.03-0.15 off
between rows (32 by square roots: under 0.004).

    python utils/sheen_albedo_table.py   (from native/vk_gltf_renderer; about two minutes)
"""

import os

import numpy as np

RES = 32
SAMPLES = 1000 * 1000  # stratified per cell; the flip is taken by its expectation, not drawn
MIN_ROUGHNESS = 0.0014142  # MICROFACET_MIN_ROUGHNESS, which the material clamps sheenRoughness to


def carried(h, k1):
    """brdf_sheen_sample's bsdf_over_pdf (G12 / G1) for half vectors h, 0 where it absorbs."""
    nk1 = k1[2]
    k1h = h @ k1
    k2 = 2.0 * k1h[:, None] * h - k1
    nk2 = k2[:, 2]
    k2h = np.abs(np.einsum("ij,ij->i", k2, h))
    nh = h[:, 2]
    ok = (nh != 0.0) & (k1h > 0.0) & (nk2 > 0.0)
    with np.errstate(divide="ignore", invalid="ignore"):
        g1 = np.minimum(2.0 * nh * nk1 / k1h, 1.0)
        g2 = np.minimum(2.0 * nh * nk2 / k2h, 1.0)
        g12 = np.minimum(g1, g2)
        w = np.where(ok & (g12 > 0.0), g12 / g1, 0.0)
    return np.nan_to_num(w)


def albedo(roughness, nov):
    roughness = max(roughness, MIN_ROUGHNESS)
    inv = 1.0 / (roughness * roughness)
    nov = max(nov, 1e-4)
    k1 = np.array([np.sqrt(1.0 - nov * nov), 0.0, nov])
    n = int(np.sqrt(SAMPLES))
    g = (np.arange(n) + 0.5) / n
    u1, u2 = np.meshgrid(g, g)
    u1, u2 = u1.ravel(), u2.ravel()
    # hvd_sheen_sample
    phi = 2.0 * np.pi * u1
    sin_t = (1.0 - u2) ** (1.0 / (inv + 2.0))
    cos_t = np.sqrt(np.maximum(1.0 - sin_t * sin_t, 0.0))
    h = np.stack([np.cos(phi) * sin_t, np.sin(phi) * sin_t, cos_t], axis=1)
    h /= np.linalg.norm(h, axis=1, keepdims=True)
    # flip: toward the view with probability kh_f / (kh + kh_f); 0 / 0 never flips (NaN compares false)
    a = h[:, 2] * k1[2]
    b = h[:, 0] * k1[0] + h[:, 1] * k1[1]
    kh = np.maximum(0.0, a + b)
    kh_f = np.maximum(0.0, a - b)
    with np.errstate(divide="ignore", invalid="ignore"):
        p_flip = np.where(kh + kh_f > 0.0, kh_f / (kh + kh_f), 0.0)
    flipped = h * np.array([-1.0, -1.0, 1.0])
    return float((p_flip * carried(flipped, k1) + (1.0 - p_flip) * carried(h, k1)).mean())


def table(values):
    rows = []
    for i in range(RES):
        rows.append("  " + ", ".join(f"{x:.5f}F" for x in values[i]) + ",")
    return "\n".join(rows)


def main():
    e = np.zeros((RES, RES))
    for i in range(RES):
        for j in range(RES):
            e[i, j] = albedo((i / (RES - 1)) ** 2, (j / (RES - 1)) ** 2)
    out = os.path.join(os.path.dirname(__file__), "..", "..", "nvpro_core2", "nvshaders", "sheen_albedo_table.h.slang")
    with open(out, "w", newline="\n") as f:
        f.write(f"""/*
 * SPDX-FileCopyrightText: Copyright (c) 2026, Figure Viewer contributors.
 * SPDX-License-Identifier: Apache-2.0
 */

// Generated by vk_gltf_renderer/utils/sheen_albedo_table.py: do not edit.
//
// The directional albedo of the sheen lobe (brdf_sheen_sample: Charlie half vectors, v-cavities
// masking) with a white sheen colour. Rows: sqrt(perceptual sheen roughness) from 0 to 1 (0 is
// MICROFACET_MIN_ROUGHNESS); columns: sqrt(N.V) from 0 to 1; {RES} each.
#ifndef SHEEN_ALBEDO_TABLE_H
#define SHEEN_ALBEDO_TABLE_H

#define SHEEN_ALBEDO_TABLE_RES {RES}

static const float SHEEN_ALBEDO[{RES * RES}] = {{
{table(e)}
}};

#endif
""")
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
