"""Writes src/star_catalog.inc, the night sky's stars, from the Yale Bright Star Catalogue (5th revised
edition, Hoffleit & Warren 1991; public domain; http://tdc-www.harvard.edu/catalogs/bsc5.html):
every star down to the eye's limit on a dark night, V 6.5, with its J2000 place, its V magnitude and
its B-V colour (0.6, a sunlike star's, where the catalogue has none).

    python -I utils/make_star_catalog.py <bsc5.dat.gz> src/star_catalog.inc
"""
import gzip
import sys

LIMIT = 6.5

rows = []
with gzip.open(sys.argv[1], "rt", encoding="latin-1") as f:
    for line in f:
        try:
            rah, ram, ras = int(line[75:77]), int(line[77:79]), float(line[79:83])
            sign = -1.0 if line[83] == "-" else 1.0
            ded, dem, des = int(line[84:86]), int(line[86:88]), int(line[88:90])
            vmag = float(line[102:107])
        except ValueError:
            continue  # the catalogue's few entries with no place (novae, galaxies, clusters once listed)
        if vmag > LIMIT:
            continue
        bv_text = line[109:114].strip()
        bv = float(bv_text) if bv_text else 0.6
        ra = 15.0 * (rah + ram / 60.0 + ras / 3600.0)
        dec = sign * (ded + dem / 60.0 + des / 3600.0)
        rows.append((ra, dec, vmag, bv))
rows.sort(key=lambda r: r[2])

with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as out:
    out.write("// Generated by utils/make_star_catalog.py from the Yale Bright Star Catalogue (5th revised edition,\n")
    out.write("// Hoffleit & Warren 1991, public domain): right ascension and declination (J2000, degrees), V magnitude,\n")
    out.write(f"// B-V; every star to V {LIMIT}, brightest first. {len(rows)} stars. Do not edit: run the script again.\n")
    for ra, dec, v, bv in rows:
        out.write(f"{{{ra:.4f}f, {dec:.4f}f, {v:.2f}f, {bv:.2f}f}},\n")
print(len(rows), "stars")
