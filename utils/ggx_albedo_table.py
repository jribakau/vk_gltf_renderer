"""Bakes nvshaders/ggx_albedo_table.h.slang: the directional albedo of the path tracer's GGX
reflection lobe (brdf_ggx_smith_sample: VNDF sampling, height-correlated Smith) with Schlick's
Fresnel, as a scale on f0 and a bias, over perceptual roughness sqrt(alpha) and sqrt(N.V).

    python utils/ggx_albedo_table.py   (from native/vk_gltf_renderer; about two minutes)
"""

import os

import numpy as np

RES = 16
SAMPLES = 1000 * 1000  # stratified per cell: the albedo to about 1e-4


def smith_lambda(k, alpha):
    tan2 = (1.0 - k[..., 2] ** 2) / np.maximum(k[..., 2] ** 2, 1e-12)
    return (np.sqrt(1.0 + alpha * alpha * tan2) - 1.0) / 2.0


def sample_vndf(v, alpha, u1, u2):
    """hvd_ggx_sample_vndf (pbr_ggx_microfacet.h.slang), isotropic."""
    vh = np.array([alpha * v[0], alpha * v[1], v[2]])
    vh /= np.linalg.norm(vh)
    t1 = np.cross(vh, [0.0, 0.0, 1.0])
    t1 = t1 / np.linalg.norm(t1) if vh[2] < 0.99999 else np.array([1.0, 0.0, 0.0])
    t2 = np.cross(t1, vh)
    a = 1.0 / (1.0 + vh[2])
    r = np.sqrt(u1)
    phi = np.where(u2 < a, u2 / a * np.pi, np.pi + (u2 - a) / (1.0 - a) * np.pi)
    p1 = r * np.cos(phi)
    p2 = r * np.sin(phi) * np.where(u2 < a, 1.0, vh[2])
    h = p1[:, None] * t1 + p2[:, None] * t2 + np.sqrt(np.maximum(0.0, 1.0 - p1 * p1 - p2 * p2))[:, None] * vh
    h[:, 0] *= alpha
    h[:, 1] *= alpha
    h[:, 2] = np.maximum(h[:, 2], 0.0)
    return h / np.linalg.norm(h, axis=1, keepdims=True)


def scale_bias(alpha, nov):
    """The lobe's albedo with Schlick's Fresnel from f0: f0 * scale + bias."""
    nov = max(nov, 1e-4)
    v = np.array([np.sqrt(1.0 - nov * nov), 0.0, nov])
    if alpha <= 0.0:
        f = (1.0 - nov) ** 5
        return 1.0 - f, f
    n = int(np.sqrt(SAMPLES))
    g = (np.arange(n) + 0.5) / n
    u1, u2 = np.meshgrid(g, g)
    h = sample_vndf(v, alpha, u1.ravel(), u2.ravel())
    kh = h @ v
    l = 2.0 * kh[:, None] * h - v
    ok = (l[:, 2] > 0.0) & (kh > 0.0)
    l1 = smith_lambda(v, alpha)
    l2 = smith_lambda(l, alpha)
    weight = np.where(ok, (1.0 + l1) / (1.0 + l1 + l2), 0.0)  # G2 / G1, the VNDF sample's
    f = (1.0 - np.clip(kh, 0.0, 1.0)) ** 5
    return (weight * (1.0 - f)).mean(), (weight * f).mean()


def table(values):
    rows = []
    for i in range(RES):
        rows.append("  " + ", ".join(f"{x:.5f}F" for x in values[i]) + ",")
    return "\n".join(rows)


def main():
    scale = np.zeros((RES, RES))
    bias = np.zeros((RES, RES))
    for i in range(RES):
        for j in range(RES):
            scale[i, j], bias[i, j] = scale_bias((i / (RES - 1)) ** 2, (j / (RES - 1)) ** 2)
    out = os.path.join(os.path.dirname(__file__), "..", "..", "nvpro_core2", "nvshaders", "ggx_albedo_table.h.slang")
    with open(out, "w", newline="\n") as f:
        f.write(f"""/*
 * SPDX-FileCopyrightText: Copyright (c) 2026, Figure Viewer contributors.
 * SPDX-License-Identifier: Apache-2.0
 */

// Generated by vk_gltf_renderer/utils/ggx_albedo_table.py: do not edit.
//
// The directional albedo of the GGX reflection lobe (brdf_ggx_smith_sample: VNDF sampling,
// height-correlated Smith) with Schlick's Fresnel from f0, as f0 * scale + bias. Rows: perceptual
// roughness sqrt(alpha) from 0 to 1; columns: sqrt(N.V) from 0 to 1; {RES} each.
#ifndef GGX_ALBEDO_TABLE_H
#define GGX_ALBEDO_TABLE_H

#define GGX_ALBEDO_TABLE_RES {RES}

static const float GGX_ALBEDO_SCALE[{RES * RES}] = {{
{table(scale)}
}};

static const float GGX_ALBEDO_BIAS[{RES * RES}] = {{
{table(bias)}
}};

#endif
""")
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
